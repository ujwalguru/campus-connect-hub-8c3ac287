const INDEX: Record<string, number> = { hi: 0, ta: 1, te: 2, bn: 3, mr: 4 };

export function translate(text: string, lang: string): string {
  if (lang === "en") return text;
  const i = INDEX[lang];
  if (i === undefined) return text;
  return DICT[text]?.[i] ?? text;
}

function readLang() {
  if (typeof localStorage === "undefined") return "en";
  return localStorage.getItem(LANG_KEY) ?? "en";
}

export function useLanguage() {
  const [lang, setLang] = useState("en");

  useEffect(() => {
    setLang(readLang());
    const sync = () => setLang(readLang());
    window.addEventListener(LANG_EVENT, sync);
    window.addEventListener("storage", sync);
    return () => {
      window.removeEventListener(LANG_EVENT, sync);
      window.removeEventListener("storage", sync);
    };
  }, []);

  const change = useCallback((code: string) => {
    localStorage.setItem(LANG_KEY, code);
    document.documentElement.lang = code;
    window.dispatchEvent(new Event(LANG_EVENT));
  }, []);

  const current = languages.find((l) => l.code === lang) ?? languages[0]!;
  const t = useCallback((text: string) => translate(text, lang), [lang]);

  return { lang, current, change, t, languages };
}

export function useT() {
  const { t, lang } = useLanguage();
  return { t, lang };
}
